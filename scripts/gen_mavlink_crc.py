"""Generate propwash-core/src/format/mavlink/crc_extra.rs from MAVLink's XML.

Reads all.xml and everything it includes, computes each message's CRC_EXTRA
the way mavgen does, and writes a sorted (id, CRC_EXTRA) table.

    python3 scripts/gen_mavlink_crc.py path/to/mavlink [--check]

path/to/mavlink is a checkout of https://github.com/mavlink/mavlink. The file
is only rewritten when a message was added, removed or changed. With --check,
nothing is written and the exit code is 1 if the table is out of date.
Uses only the Python standard library.
"""

import os
import subprocess
import sys
import xml.etree.ElementTree as ET

OUT = "propwash-core/src/format/mavlink/crc_extra.rs"
DEFS = os.path.join("message_definitions", "v1.0")
TYPE_LEN = {
    "char": 1, "uint8_t": 1, "int8_t": 1, "uint8_t_mavlink_version": 1,
    "uint16_t": 2, "int16_t": 2,
    "uint32_t": 4, "int32_t": 4, "float": 4,
    "uint64_t": 8, "int64_t": 8, "double": 8,
}


def x25(data, crc=0xFFFF):
    for b in data:
        t = (b ^ crc) & 0xFF
        t = (t ^ (t << 4)) & 0xFF
        crc = ((crc >> 8) ^ (t << 8) ^ (t << 3) ^ (t >> 4)) & 0xFFFF
    return crc


def crc_extra(msg):
    """CRC_EXTRA as mavgen computes it: name, then each core (non-extension)
    field in wire order (stable sort by element size, largest first) as
    "type name " plus the array length byte for arrays."""
    fields = []
    for child in msg:
        if child.tag == "extensions":
            break
        if child.tag != "field":
            continue
        ftype, n = child.get("type"), None
        if "[" in ftype:
            ftype, n = ftype[:-1].split("[")
            n = int(n)
        fields.append((ftype, child.get("name"), n))
    fields.sort(key=lambda f: -TYPE_LEN[f[0]])
    crc = x25((msg.get("name") + " ").encode())
    for ftype, fname, n in fields:
        if ftype == "uint8_t_mavlink_version":
            ftype = "uint8_t"
        crc = x25((ftype + " ").encode(), crc)
        crc = x25((fname + " ").encode(), crc)
        if n is not None:
            crc = x25(bytes([n]), crc)
    return (crc & 0xFF) ^ (crc >> 8)


def load(root):
    msgs, seen = {}, set()

    def visit(name):
        if name in seen:
            return
        seen.add(name)
        tree = ET.parse(os.path.join(root, DEFS, name)).getroot()
        for inc in tree.findall("include"):
            visit(inc.text.strip())
        for msg in tree.iter("message"):
            mid, extra = int(msg.get("id")), crc_extra(msg)
            prev = msgs.get(mid)
            if prev and prev[0] != extra:
                sys.exit(f"id {mid} defined twice: {prev[1]} and {msg.get('name')}")
            msgs[mid] = (extra, msg.get("name"))

    visit("all.xml")
    return msgs


def render(root, msgs):
    sha = subprocess.run(["git", "-C", root, "rev-parse", "HEAD"],
                         capture_output=True, text=True, check=True).stdout.strip()
    lines = [
        "//! `CRC_EXTRA` for every message in `MAVLink`'s `all.xml` dialect.",
        "//!",
        "//! Generated by `scripts/gen_mavlink_crc.py` from `mavlink/mavlink` at",
        f"//! `{sha}`. Do not edit by hand.",
        "",
        "/// `(message id, CRC_EXTRA)`, sorted by id.",
        "#[rustfmt::skip]",
        "pub(super) static CRC_EXTRA: &[(u32, u8)] = &[",
    ]
    lines += [f"    ({mid}, {extra}), // {name}" for mid, (extra, name) in sorted(msgs.items())]
    lines.append("];")
    return "\n".join(lines) + "\n"


def table_lines(text):
    """The table without the header comment, whose commit hash changes on
    every upstream commit even when no message changed."""
    return [l for l in text.splitlines() if not l.startswith("//! ")]


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        sys.exit(__doc__)
    msgs = load(args[0])
    text = render(args[0], msgs)
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if table_lines(old) == table_lines(text):
        print(f"{OUT} is up to date ({len(msgs)} messages)")
        return
    if "--check" in sys.argv:
        print(f"{OUT} is out of date with mavlink/mavlink")
        sys.exit(1)
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print(f"wrote {len(msgs)} messages to {OUT}")


if __name__ == "__main__":
    main()
